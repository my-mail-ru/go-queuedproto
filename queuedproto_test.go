func TestAddItem(t *testing.T) {
	addItem := ReqAddItem{
		Pid:         1,
		ReqID:       2,
		StorageType: 100,
		ID:          3,
		UnixTime:    1601882024,
		Data:        []byte(`000`),
	}

	need := []byte{
		0x01, 0x00, 0x00, 0x00,
		0x02, 0x00, 0x00, 0x00,
		0x64, 0x00,
		0x03, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
		0xA8, 0xC7, 0x7A, 0x5F,
		0x03, 0x00,
		0x30, 0x30, 0x30,
	}

	got, err := addItem.MarshalIProto(nil)
	if err != nil {
		t.Fatal(err)
	}

	if !bytes.Equal(got, need) {
		t.Errorf("ADD_ITEM not match %+v\ngot:\t[% x]\nneed:\t[% x]", addItem, got, need)
	}
}

